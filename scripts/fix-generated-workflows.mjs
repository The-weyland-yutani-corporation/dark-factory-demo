import { readFile, readdir, writeFile } from "node:fs/promises";

const workflowRoot = ".github/workflows";
const lockFiles = (await readdir(workflowRoot))
  .filter((name) => name.endsWith(".lock.yml"))
  .map((name) => `${workflowRoot}/${name}`);

for (const lockFile of lockFiles) {
  let lockContent = await readFile(lockFile, "utf8");
  for (const retired of [
    "${{ secrets.GH_AW_AGENT_TOKEN || secrets.GH_AW_GITHUB_TOKEN || secrets.GITHUB_TOKEN }}",
    "${{ secrets.GH_AW_GITHUB_MCP_SERVER_TOKEN || secrets.GH_AW_GITHUB_TOKEN || secrets.GITHUB_TOKEN }}",
    "${{ secrets.GH_AW_GITHUB_TOKEN }}",
    "${{ secrets.GH_AW_GITHUB_MCP_SERVER_TOKEN }}",
  ]) {
    lockContent = lockContent.replaceAll(
      retired,
      "${{ secrets.GITHUB_TOKEN }}",
    );
  }
  for (const retiredManifestEntry of [
    '"GH_AW_AGENT_TOKEN",',
    '"GH_AW_GITHUB_MCP_SERVER_TOKEN",',
    '"GH_AW_GITHUB_TOKEN",',
  ]) {
    lockContent = lockContent.replaceAll(retiredManifestEntry, "");
  }
  lockContent = lockContent.replace(
    /^#[ ]{3}- GH_AW_(?:AGENT_TOKEN|GITHUB_MCP_SERVER_TOKEN|GITHUB_TOKEN)\r?\n/gm,
    "",
  );
  if (
    lockContent.includes("assign-to-agent") ||
    lockContent.includes("assign_to_agent")
  ) {
    throw new Error(`${lockFile} contains unsupported assign-to-agent output`);
  }
  const codeWritingOutput = lockFile.endsWith(
    "coding-agent-assignment.lock.yml",
  )
    ? "create_pull_request"
    : lockFile.endsWith("bounded-repair-routing.lock.yml")
      ? "push_to_pull_request_branch"
      : undefined;
  if (codeWritingOutput) {
    for (const expected of [
      codeWritingOutput,
      "DARK_FACTORY_MAGE_APP_PRIVATE_KEY",
      "permission-contents: write",
      "permission-workflows: write",
      "GH_AW_CI_TRIGGER_TOKEN: ${{ steps.safe-outputs-app-token.outputs.token || '' }}",
    ]) {
      if (!lockContent.includes(expected)) {
        throw new Error(`${lockFile} is missing ${expected}`);
      }
    }
    if (/GH_AW_CI_TRIGGER_TOKEN:\s*\$\{\{\s*secrets\./.test(lockContent)) {
      throw new Error(`${lockFile} uses a secret/PAT CI trigger fallback`);
    }
  }
  await writeFile(lockFile, lockContent);
}

const file = `${workflowRoot}/agentics-maintenance.yml`;
let content;
try {
  content = await readFile(file, "utf8");
} catch (error) {
  if (error.code === "ENOENT") process.exit(0);
  throw error;
}

const marker =
  "# Deterministic repository hardening applied by scripts/fix-generated-workflows.mjs";
if (!content.startsWith("# This file was automatically generated by")) {
  throw new Error(`${file} is not a recognized generated maintenance workflow`);
}

let lines = content.split(/\r?\n/);
if (!lines.includes(marker)) {
  const permissions = lines.indexOf("permissions: {}");
  if (permissions < 0) throw new Error(`${file} has no permissions boundary`);
  lines.splice(
    permissions,
    0,
    marker,
    "concurrency:",
    "  group: agentic-maintenance-${{ github.event_name }}-${{ inputs.operation || 'scheduled' }}",
    "  cancel-in-progress: false",
    "",
  );
}

const jobsIndex = lines.indexOf("jobs:");
for (let index = jobsIndex + 1; index < lines.length;) {
  if (!/^ {2}[A-Za-z0-9_-]+:$/.test(lines[index])) {
    index += 1;
    continue;
  }
  let end = index + 1;
  while (end < lines.length && !/^ {2}[A-Za-z0-9_-]+:$/.test(lines[end])) {
    end += 1;
  }
  const block = lines.slice(index, end);
  const runnerOffset = block.findIndex((line) => /^ {4}runs-on:/.test(line));
  const timeoutExists = block.some((line) =>
    /^ {4}timeout-minutes:/.test(line),
  );
  if (runnerOffset >= 0 && !timeoutExists) {
    lines.splice(index + runnerOffset + 1, 0, "    timeout-minutes: 30");
    end += 1;
  }
  index = end;
}

content = lines.join("\n");
const replayJobStart = content.indexOf("  apply_safe_outputs:");
const replayJobEnd = content.indexOf("\n  create_labels:", replayJobStart);
if (replayJobStart >= 0 && replayJobEnd > replayJobStart) {
  let replayJob = content.slice(replayJobStart, replayJobEnd);
  replayJob = replayJob
    .replace("      contents: write", "      contents: read")
    .replace("      discussions: write", "      discussions: read")
    .replace("      issues: write", "      issues: read")
    .replace("      pull-requests: write", "      pull-requests: read");
  if (!replayJob.includes("        id: replay-token")) {
    replayJob = replayJob.replace(
      "      - name: Apply Safe Outputs",
      [
        "      - name: Mint repository-scoped replay token",
        "        id: replay-token",
        "        uses: actions/create-github-app-token@bcd2ba49218906704ab6c1aa796996da409d3eb1 # v3.2.0",
        "        with:",
        "          client-id: ${{ vars.DARK_FACTORY_MAGE_APP_CLIENT_ID }}",
        "          private-key: ${{ secrets.DARK_FACTORY_MAGE_APP_PRIVATE_KEY }}",
        "          owner: ${{ github.repository_owner }}",
        "          repositories: ${{ github.event.repository.name }}",
        "          permission-discussions: write",
        "          permission-issues: write",
        "          permission-pull-requests: write",
        "",
        "      - name: Apply Safe Outputs",
      ].join("\n"),
    );
  }
  replayJob = replayJob
    .replace(
      "          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}",
      "          GH_TOKEN: ${{ steps.replay-token.outputs.token }}",
    )
    .replace(
      "          github-token: ${{ secrets.GITHUB_TOKEN }}\n          script: |\n            const { setupGlobals } = require('${{ runner.temp }}/gh-aw/actions/setup_globals.cjs');\n            setupGlobals(core, github, context, exec, io, getOctokit);\n            const { main } = require('${{ runner.temp }}/gh-aw/actions/apply_safe_outputs_replay.cjs');",
      "          github-token: ${{ steps.replay-token.outputs.token }}\n          script: |\n            const { setupGlobals } = require('${{ runner.temp }}/gh-aw/actions/setup_globals.cjs');\n            setupGlobals(core, github, context, exec, io, getOctokit);\n            const { main } = require('${{ runner.temp }}/gh-aw/actions/apply_safe_outputs_replay.cjs');",
    );
  content =
    content.slice(0, replayJobStart) + replayJob + content.slice(replayJobEnd);
}

await writeFile(file, `${content.replace(/\n+$/, "")}\n`);
